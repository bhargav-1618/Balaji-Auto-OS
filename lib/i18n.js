// {name}-style interpolation — kept intentionally tiny (no ICU/plural rules
// engine): this app's dynamic strings are simple counts/ranges, not the kind of
// grammar-sensitive pluralization that would justify pulling in a library.
function interpolate(str, params) {
  if (!params) return str;
  return str.replace(/\{(\w+)\}/g, (m, key) => (params[key] !== undefined ? String(params[key]) : m));
}

const SETTINGS_KEY = (demoMode) => (demoMode ? 'maruti_settings_demo' : 'maruti_settings');

function readLocale(demoMode) {
  if (typeof window === 'undefined') return DEFAULT_LOCALE;
  try {
    const raw = JSON.parse(localStorage.getItem(SETTINGS_KEY(demoMode)) || '{}');
    return LOCALES[raw.language] ? raw.language : DEFAULT_LOCALE;
  } catch {
    return DEFAULT_LOCALE;
  }
}

const LanguageContext = createContext({ locale: DEFAULT_LOCALE, t: (key, fallback) => fallback ?? key });

// `demoMode` is accepted as a prop (rather than this provider importing useAuth
// itself) so lib/i18n.js has no dependency on context/AuthContext.js — the same
// "keep primitives content/consumer-agnostic" discipline already used for
// DropdownPanel/ActionMenu in components/common. AuthProvider already sits above
// this in pages/_app.js and can pass its own demoMode straight through.
export function LanguageProvider({ demoMode = false, children }) {
  const [locale, setLocaleState] = useState(() => readLocale(demoMode));

  // Re-read whenever demoMode itself changes (switching in/out of the isolated
  // demo settings blob) or when ANY settings save fires — the exact same event
  // saveBiz() already dispatches for every other Business Profile field, so this
  // needs no new plumbing.
  useEffect(() => { setLocaleState(readLocale(demoMode)); }, [demoMode]);
  useEffect(() => {
    const onSettings = () => setLocaleState(readLocale(demoMode));
    window.addEventListener('maruti-settings', onSettings);
    window.addEventListener('storage', onSettings);
    return () => {
      window.removeEventListener('maruti-settings', onSettings);
      window.removeEventListener('storage', onSettings);
    };
  }, [demoMode]);

  // NO setLocale/direct-write function is exposed here — deliberately. Language is
  // a normal staged Business Profile field like every other (Workshop Name, GST
  // Number, ...): the Settings page holds the staged value in its own `biz` state,
  // Save Changes persists the WHOLE biz object exactly as it already does for
  // every other field (via the SAME saveBiz()/localStorage.setItem/
  // 'maruti-settings' dispatch this provider already listens for above), and only
  // THEN does the active `locale` here update. There is deliberately no second way
  // to change the persisted/active locale — a dropdown (or anything else) calling
  // straight into localStorage here would be exactly the kind of parallel
  // persistence path/"duplicate language state that can drift" this file exists to
  // avoid. Cancelling in Settings (discarding the staged biz back to its saved
  // baseline) requires no special handling either: since selecting a language never
  // touches this provider's state pre-save, there is nothing to revert.
  const t = useCallback((key, fallback, params) => {
    if (locale === DEFAULT_LOCALE) return interpolate(fallback ?? key, params);
    const dict = DICTS[locale];
    const hit = dict && dict[key];
    if (hit === undefined) {
      if (process.env.NODE_ENV !== 'production') {
        // Dev-time missing-key signal (Issue: "add a development-time way to
        // detect missing translation keys") — never thrown, never surfaced to a
        // real user; production silently falls back to the caller's English text.
        // eslint-disable-next-line no-console
        console.warn(`[i18n] missing "${locale}" translation for key "${key}" — falling back to English.`);
      }
      return interpolate(fallback ?? key, params);
    }
    return interpolate(hit, params);
  }, [locale]);

  const value = useMemo(() => ({ locale, t, locales: LOCALES }), [locale, t]);
  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useTranslation() {
  return useContext(LanguageContext);
}
