// CENTRALIZED LOCALIZATION — the ONE language/translation source for the whole app.
// Audited first (see PR description / commit notes): no i18n system, translation
// file, locale state, or `if (language === 'Hindi')` branching existed anywhere in
// the codebase before this file. This is not a second competing system layered on
// top of something else — it is the first and only one.
//
// Architecture (matches the shape every reviewer asked for):
//   selected locale → LanguageProvider (React Context) → t(key, fallback, params)
//   → every consumer that calls useTranslation().
//
// Locale source of truth: the SAME per-mode settings blob every other Business
// Profile field already persists to (`maruti_settings` / `maruti_settings_demo` in
// localStorage), read via the field the Settings page already writes:
// `biz.language`. No second, competing "language" key was introduced. Changing the
// language is applied INSTANTLY (like the existing Appearance prefs — theme/font
// size/reduce-motion — which also apply without a separate "Save Changes" step),
// broadcast through the SAME `maruti-settings` CustomEvent the Settings page's own
// saveBiz() already dispatches, so every mounted component reacts without a page
// reload and without prop-drilling.
//
// English is never duplicated into a dictionary: every call site already owns its
// English string (it was already hard-coded there before this file existed) and
// passes it to t() as the `fallback` argument. t() only ever needs to answer "is
// there a hi/te override for this key?" — if not, the caller's own English string
// is returned as-is. This is why introducing localization did not require rewriting
// a single English word anywhere in the app.
